# --- 怪物变体修饰 ---
# (修饰词, 等级变化, 格式: 0=前缀, 1=后缀)
MONSTER_MODIFIERS = [
    ("胚胎的", -4, 0),
    ("垂死的", -4, 0),
    ("残废的", -3, 0),
    ("幼年的", -3, 0),
    ("少年的", -2, 0),
    ("病弱的", -2, 0),
    ("下位的", -1, 0),
    ("营养不良的", -1, 0),
    ("上位的", 1, 0),
    ("长老", 1, 1),           # {name} 长老
    ("战斗", 2, 0),           # 战斗{name}
    ("战狂", 2, 0),           # 战狂{name}
    ("狼化", 3, 0),           # 狼化{name}
    ("亡灵", 3, 0),           # 亡灵{name}
    ("巨型", 4, 0),           # 巨型{name}
    ("霸主", 4, 1),           # {name} 霸主
]


def random_monster_mod():
    """返回一个随机变体修饰 (name, level_delta, format_type)"""
    return random.choice(MONSTER_MODIFIERS)


def get_monster_by_name(name: str):
    """根据名称查找怪物模板"""
    for m in MONSTERS:
        if m[0] == name:
            return m
    return None


def get_random_monster():
    """返回一个随机怪物模板"""
    return random.choice(MONSTERS)


def pick_monster_for_level(player_level: int):
    """
    根据玩家等级选择一个合适等级的怪物，并应用随机变体。
    返回: (怪物名, 等级, max_hp, attack, defense, xp, loot_table)
    """
    # 选择与玩家等级正负5级范围内的怪物
    candidates = [m for m in MONSTERS if abs(m[1] - player_level) <= 5]
    if not candidates:
        candidates = MONSTERS

    base_name, base_level, loot = random.choice(candidates)

    # 随机变体
    mod_name, level_delta, fmt_type = random_monster_mod()
    if fmt_type == 0:
        final_name = f"{mod_name} {base_name}"
    else:
        final_name = f"{base_name} {mod_name}"

    final_level = max(1, base_level + level_delta)

    # 属性基于等级计算
    final_hp = int(30 + final_level * 12 + random.randint(-10, 10))
    final_attack = int(5 + final_level * 2.5 + random.randint(-3, 3))
    final_defense = int(2 + final_level * 1.5 + random.randint(-2, 2))
    final_xp = int(final_level * 15 + random.randint(-10, 10))

    return final_name, final_level, final_hp, final_attack, final_defense, final_xp, list(loot)


# --- 等级/掉落查找：用于任务系统按玩家等级筛选 ---

# 怪物名 -> 基础等级
_MONSTER_LEVEL_MAP = {m[0].lower(): m[1] for m in MONSTERS}

# 掉落物 -> (怪物名, 基础等级)
_LOOT_TO_MONSTER = {}
for name, level, loot in MONSTERS:
    for item in loot:
        if item not in _LOOT_TO_MONSTER:
            _LOOT_TO_MONSTER[item] = (name, level)


def get_monster_base_level(name: str) -> int:
    """根据怪物名（大小写不敏感）返回基础等级"""
    return _MONSTER_LEVEL_MAP.get(name.lower(), 1)


def get_loot_monster_level(loot_name: str) -> int:
    """根据掉落物名返回掉落该物品的怪物基础等级"""
    info = _LOOT_TO_MONSTER.get(loot_name)
    return info[1] if info else 1


def get_target_level(target: str, target_type: str) -> int:
    """
    根据任务目标的类型和名称，返回该目标对应的怪物基础等级。
    击杀任务：直接查怪物等级
    收集任务：查掉落物所属怪物等级
    """
    if target_type == "击杀":
        return get_monster_base_level(target)
    else:  # 收集
        return get_loot_monster_level(target)
