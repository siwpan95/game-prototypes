"""StealthSystem - Noise calculation, cover, and enemy alert mechanics."""
import random
from typing import List, Optional

from core.constants import NOISE_THRESHOLD, NOISE_DECAY
from core.game_state import GameState
from models.player import Player
from models.room import Room
from models.enemy import Enemy


class StealthSystem:
    """Handles noise generation, cover mechanics, and enemy alert states."""

    # Noise values per action type
    NOISE_MAP = {
        "move": 2,
        "fire": None,       # Uses weapon.noise_generated()
        "grenade": 5,
        "sneak": 1,
        "reload": 0,
        "aim": 0,
        "use_item": 0,
        "take_cover": 0,
    }

    def __init__(self) -> None:
        pass

    def calculate_noise(self, player: Player, action: str) -> int:
        """Calculate noise generated by an action.

        For 'fire', uses the current weapon's noise_generated().
        Returns noise value.
        """
        base = self.NOISE_MAP.get(action, 0)
        if base is None and action == "fire":
            weapon = player.current_weapon()
            return weapon.noise_generated() if weapon else 3
        return base if base is not None else 0

    def apply_noise(self, player: Player, action: str) -> dict:
        """Apply noise from an action to the player.

        Returns dict with noise_added, total_noise, alerted.
        """
        noise = self.calculate_noise(player, action)
        player.noise_level += noise
        alerted = player.noise_level > NOISE_THRESHOLD

        if alerted:
            pass  # (F4) event publish removed; alerted still returned below

        return {
            "noise_added": noise,
            "total_noise": player.noise_level,
            "alerted": alerted,
        }

    def decay_noise(self, player: Player) -> None:
        """Reduce player noise level at end of each turn."""
        player.noise_level = max(0, player.noise_level - NOISE_DECAY)

    def check_alert(self, game_state: GameState) -> List[Enemy]:
        """Check if noise attracts enemies from adjacent rooms.

        If player noise > NOISE_THRESHOLD, move 1-2 enemies from
        adjacent rooms into the current room.
        Returns list of enemies that were attracted.
        """
        player = game_state.player
        current_room = game_state.current_room
        if player is None or current_room is None:
            return []

        if player.noise_level <= NOISE_THRESHOLD:
            return []

        level = game_state.levels[-1] if game_state.levels else None
        if level is None:
            return []

        # Find adjacent rooms with enemies
        adjacent_enemies: List[tuple] = []  # (enemy, room)
        for direction, room_id in current_room.exits.items():
            adj_room = level.get_room(room_id)
            if adj_room is None:
                continue
            for enemy in adj_room.living_enemies():
                adjacent_enemies.append((enemy, adj_room))

        if not adjacent_enemies:
            return []

        # Attract 1-2 enemies
        count = min(random.randint(1, 2), len(adjacent_enemies))
        attracted: List[Enemy] = []

        # Shuffle and pick
        random.shuffle(adjacent_enemies)
        for enemy, adj_room in adjacent_enemies[:count]:
            adj_room.remove_enemy(enemy)
            current_room.enemies.append(enemy)
            attracted.append(enemy)

        return attracted

    def take_cover(self, player: Player, room: Room) -> dict:
        """Player takes cover behind available cover objects.

        Returns dict with success, message.
        """
        if player.in_cover:
            return {
                "success": False,
                "message": "你已经在掩体中了。",
            }

        if not room.has_cover():
            return {
                "success": False,
                "message": "这个房间没有可用的掩体。",
            }

        player.in_cover = True
        cover_name = room.cover_objects[0]

        return {
            "success": True,
            "message": f"你躲在了{cover_name}后面。（敌人命中率-20%）",
        }

    def leave_cover(self, player: Player) -> dict:
        """Player leaves cover. Returns dict with success, message."""
        if not player.in_cover:
            return {
                "success": False,
                "message": "你并不在掩体中。",
            }
        player.in_cover = False
        return {
            "success": True,
            "message": "你离开了掩体，重新暴露。",
        }

    def toggle_cover(self, player: Player, room: Room) -> dict:
        """Toggle cover state. Returns dict with success, message, now_in_cover."""
        if player.in_cover:
            result = self.leave_cover(player)
            result["now_in_cover"] = False
            return result
        result = self.take_cover(player, room)
        result["now_in_cover"] = player.in_cover
        return result
